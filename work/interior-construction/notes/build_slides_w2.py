def vflow(labels, x=110, w=260, y0=18, h=42, gap=13, fs=16, hi=None):
    """위에서 아래로 내려가는 흐름. labels: [글자, ...] 또는 [(위, 아래), ...]"""
    els = []
    for i, lab in enumerate(labels):
        y = y0 + i * (h + gap)
        if isinstance(lab, tuple):
            lines = [(lab[0], fs, "tb"), (lab[1], 14, "tm")]
        else:
            lines = [(lab, fs, "tb")]
        els.append(BOX(x, y, w, h, lines, "box2" if hi == i else "box", i + 1))
        if i:
            els.append(A(x + w / 2.0, y - gap + 1, x + w / 2.0, y - 3, "e2", i + 1))
    return els


def hrow(labels, y=110, h=56, bw=104, gap=18, fs=15, hi=None):
    """왼쪽에서 오른쪽으로 가는 흐름."""
    n = len(labels)
    x0 = (480.0 - (n * bw + (n - 1) * gap)) / 2.0
    els = []
    for i, lab in enumerate(labels):
        x = x0 + i * (bw + gap)
        lines = [(lab[0], fs, "tb")] if isinstance(lab, tuple) else [(lab, fs, "tb")]
        if isinstance(lab, tuple) and lab[1]:
            lines.append((lab[1], 14, "tm"))
        els.append(BOX(x, y, bw, h, lines, "box2" if hi == i else "box", i + 1))
        if i:
            els.append(A(x - gap + 2, y + h / 2.0, x - 3, y + h / 2.0, "e2", i + 1))
    return els


