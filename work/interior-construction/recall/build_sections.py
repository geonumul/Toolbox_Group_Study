def dump(deck, spec, total):
    out, seen = [], []
    for big, items in spec:
        out.append({"t": big, "items": [{"t": t, "p": [a, b]} for t, a, b in items]})
        seen += [(a, b) for _, a, b in items]
    seen.sort()
    assert seen[0][0] == 1 and seen[-1][1] == total, (deck, seen[0], seen[-1])
    for (a0, b0), (a1, b1) in zip(seen, seen[1:]):
        assert a1 == b0 + 1, (deck, b0, a1)
    (OUT / f"{deck}_sections.json").write_text(json.dumps(out, ensure_ascii=False, indent=1),
                                               encoding="utf-8", newline="\n")
    print(deck, len(out), "큰 단원,", sum(len(c["items"]) for c in out), "소단원,", total, "쪽")


