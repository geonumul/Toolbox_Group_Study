bank = []
cnt = Counter()


def add(t, u, slides, **kw):
    cnt[t] += 1
    item = {"id": "wbh-%s-%03d" % (t, cnt[t]), "type": t, "part": "b", "level": "hard",
            "unit": U[u], "slides": slides, "src": "예상"}
    item.update(kw)
    bank.append(item)


RND = random.Random(20260926)


def mcq(u, q, choices, e, slides=None):
    order = list(range(4))
    RND.shuffle(order)
    add("mcq", u, slides or SL[u], q=q, c=[choices[k] for k in order], a=order.index(0), e=e)


def ox(u, q, a, e, slides=None):
    add("ox", u, slides or SL[u], q=q, a=a, e=e)


def short(u, q, a, e, slides=None, num=False):
    kw = dict(q=q, a=a, e=e)
    if num:
        kw["num"] = True
        kw["tol"] = 0.01
    add("short", u, slides or SL[u], **kw)


def essay(u, model, q, answer, points, slides=None):
    add("essay", u, slides or SL[u], model=model, q=q, answer=answer, points=points)


def calc(u, model, q, qko, blanks, steps, answer, e, slides=None):
    add("calc", u, slides or SL[u], model=model, q=q, qko=qko, blanks=blanks,
        steps=steps, answer=answer, e=e)


