def build(part, units, mcq, ox, short, essay, pre):
    rnd = random.Random(20261011 + int(part))
    out = []
    for i, (u, sl, q, c, e) in enumerate(mcq, 1):
        order = list(range(4))
        rnd.shuffle(order)
        out.append({"id": f"{pre}-mcq-{i:03d}", "type": "mcq", "part": part, "level": "basic", "unit": units[u],
                    "slides": sl, "q": q, "c": [c[k] for k in order], "a": order.index(0), "e": e})
    for i, (u, sl, q, a, e) in enumerate(ox, 1):
        out.append({"id": f"{pre}-ox-{i:03d}", "type": "ox", "part": part, "level": "basic", "unit": units[u],
                    "slides": sl, "q": q, "a": a, "e": e})
    for i, (u, sl, q, a, e) in enumerate(short, 1):
        item = {"id": f"{pre}-short-{i:03d}", "type": "short", "part": part, "level": "basic", "unit": units[u],
                "slides": sl, "q": q, "a": a, "e": e}
        try:
            float(a[0])
            item.update(num=True, tol=0.01)
        except ValueError:
            pass
        out.append(item)
    for i, (u, sl, q, ans, pts, model) in enumerate(essay, 1):
        out.append({"id": f"{pre}-essay-{i:03d}", "type": "essay", "part": part, "level": "basic", "unit": units[u],
                    "slides": sl, "q": q, "answer": ans, "points": pts, "model": model})
    return out


