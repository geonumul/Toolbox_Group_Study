def load_glossary():
    pool = {}
    for name in ("5.json", "3.json", "2.json"):
        with open(os.path.join(TERMS, name), encoding="utf-8") as f:
            for t in json.load(f):
                pool.setdefault(t["ko"], t)
    out = []
    for ko in USE:
        assert ko in pool, ko
        t = pool[ko]
        g = {"ko": t["ko"], "en": t.get("en", ""), "say": t["say"]}
        if t.get("more"):
            g["more"] = t["more"]
        out.append(g)
    have = {g["ko"] for g in out}
    for t in NEW:
        assert t["ko"] not in have and t["ko"] not in pool, t["ko"]
        out.append(t)
    return out


