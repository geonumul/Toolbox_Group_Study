GL = []
for name in ORDER:
    if name in NEW:
        GL.append(NEW[name])
        continue
    hit = next((g for g in SRC if g.get("ko") == name), None)
    assert hit is not None, name
    e = {"ko": hit["ko"], "en": hit.get("en", ""), "say": hit["say"]}
    if hit.get("more"):
        e["more"] = hit["more"]
    GL.append(e)
assert len({g["ko"] for g in GL}) == len(GL)
G = {g["ko"]: g for g in GL}


def T(k):
    """본문 표기: **한국어(English)** 또는 **한국어**"""
    g = G[k]
    return f"**{g['ko']}({g['en']})**" if g["en"] else f"**{g['ko']}**"


def ID(*ks):
    """terms 목록: en 이 있으면 en, 없으면 ko"""
    return [G[k]["en"] or G[k]["ko"] for k in ks]


