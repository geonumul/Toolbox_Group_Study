# 은행 계좌 y[n] = 1.01 y[n-1] + x[n] (단위: 만 원)
def bank(xin, N):
    y, prev = [], 0.0
    for n in range(N):
        prev = 1.01 * prev + xin(n)
        y.append(prev)
    return y
imp = bank(lambda n: 100 if n == 0 else 0, 4)
assert [round(v, 4) for v in imp] == [100, 101, 102.01, 103.0301]
stp = bank(lambda n: 100, 4)
