assert B * 2 == 2
# 누산기 뒤에 1차 차분: x=[1,2,3]
xs = [1, 2, 3]
acc = [sum(xs[:i + 1]) for i in range(3)]
assert acc == [1, 3, 6]
back = [acc[i] - (acc[i - 1] if i else 0) for i in range(3)]
assert back == xs
# 1차 차분의 임펄스 응답에 누산기: u * (delta - delta[n-1]) = delta
d = [1, -1, 0, 0]
assert [sum(d[:i + 1]) for i in range(4)] == [1, 0, 0, 0]
# 삼각 부등식
assert abs(3 + (-1)) == 2 and abs(3) + abs(-1) == 4
