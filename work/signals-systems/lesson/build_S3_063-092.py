def _fin(key):
    c = TERMS[key][0][-1]
    if "가" <= c <= "힣":
        j = (ord(c) - 0xAC00) % 28
        return 0 if j == 0 else (2 if j == 8 else 1)
    return 0 if c in "OIoi" else 1


def disp(key):
    ko, en = TERMS[key]
    return f"**{ko}({en})**"


def K(key, josa=""):
    s = disp(key)
    if not josa:
        return s
    f = _fin(key)
    if josa == "으로":
        return s + ("으로" if f == 1 else "로")
    if josa in JOSA:
        return s + (JOSA[josa][0] if f >= 1 else JOSA[josa][1])
    return s + josa


def gloss_entry(key):
    ko, en = TERMS[key]
    if key in NEW:
        return {"ko": ko, "en": en, "say": NEW[key][0], "more": NEW[key][1]}
    for d in DICT:
        if d.get("ko") == ko and d.get("en") == en:
            g = {"ko": ko, "en": en, "say": d["say"]}
            if d.get("more"):
                g["more"] = d["more"]
            return g
    raise KeyError(key)


