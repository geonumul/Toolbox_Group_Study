def _b(b):
    return f" b{b}" if b else ""


def TX(x, y, s, cls="t", fs=15, anc="middle", b=0):
    s = s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
    return f'<text x="{x}" y="{y}" font-size="{fs}" text-anchor="{anc}" class="{cls}{_b(b)}">{s}</text>'


def R(x, y, w, h, cls="box", b=0, rx=2):
    return f'<rect x="{x}" y="{y}" width="{w}" height="{h}" rx="{rx}" class="{cls}{_b(b)}"/>'


def C(x, y, r, cls="n", b=0):
    return f'<circle cx="{x}" cy="{y}" r="{r}" class="{cls}{_b(b)}"/>'


def L(x1, y1, x2, y2, cls="e", b=0):
    return f'<line x1="{x1}" y1="{y1}" x2="{x2}" y2="{y2}" class="{cls}{_b(b)}"/>'


def A(x1, y1, x2, y2, cls="e2", b=0):
    ang = math.atan2(y2 - y1, x2 - x1)
    hx, hy = x2 - 9 * math.cos(ang), y2 - 9 * math.sin(ang)
    qx, qy = -math.sin(ang) * 5, math.cos(ang) * 5
    pts = f"{x2:.0f},{y2:.0f} {hx + qx:.0f},{hy + qy:.0f} {hx - qx:.0f},{hy - qy:.0f}"
    return L(x1, y1, f"{hx:.0f}", f"{hy:.0f}", cls, b) + f'<polygon points="{pts}" class="arrow{_b(b)}"/>'


def PG(pts, cls="n", b=0):
    return f'<polygon points="{" ".join(f"{x},{y}" for x, y in pts)}" class="{cls}{_b(b)}"/>'


def PL(pts, cls="e2", b=0):
    return f'<polyline points="{" ".join(f"{x:.1f},{y:.1f}" for x, y in pts)}" fill="none" class="{cls}{_b(b)}"/>'


def BOX(x, y, w, h, label, cls="box", tcls="tb", b=0, fs=15):
    return R(x, y, w, h, cls, b) + TX(x + w / 2, y + h / 2 + fs // 3 + 1, label, tcls, fs, "middle", b)


def SVG(*parts, h=270):
    return f'<svg viewBox="0 0 480 {h}" xmlns="http://www.w3.org/2000/svg">' + "".join(parts) + "</svg>"


def stems(x0, dx, base, scale, vals, cls="n2", b=0, labels=True, nfrom=0, vlab=None):
    """이산 신호 줄기 그림. vals 는 n=nfrom 부터."""
    out = []
    for i, v in enumerate(vals):
        x = x0 + i * dx
        y = base - scale * v
        if v != 0:
            out.append(L(x, base, x, round(y, 1), "e2", b))
        out.append(C(x, round(y, 1), 4, cls, b))
        if labels:
            out.append(TX(x, base + 18, str(nfrom + i), "tm", 14, "middle", b))
        if vlab and vlab[i]:
            out.append(TX(x, round(y, 1) - 9, vlab[i], "t", 14, "middle", b))
    return "".join(out)


def ADD(x, y, r=17, b=0):
    return C(x, y, r, "n", b) + TX(x, y + 6, "+", "tb", 18, "middle", b)


def GAIN_R(x, y, label, b=0, lab_dy=-24):
    """오른쪽을 향한 곱셈기 세모. x 는 왼쪽 끝"""
    return PG([(x, y - 16), (x, y + 16), (x + 34, y)], "n3", b) + TX(x + 14, y + lab_dy, label, "tb", 15, "middle", b)


def GAIN_L(x, y, label, b=0, lab_dy=36):
    """왼쪽을 향한 곱셈기 세모. x 는 오른쪽 끝"""
    return PG([(x, y - 16), (x, y + 16), (x - 34, y)], "n3", b) + TX(x - 14, y + lab_dy, label, "tb", 15, "middle", b)


