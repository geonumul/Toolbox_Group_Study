P25_B = [1.0, 0.5, 0.25]


def diffeq(x, n):
    """y[n] = x[n] + 0.5x[n-1] + 0.25x[n-2]"""
    return sum(P25_B[i] * x.get(n - i, 0.0) for i in range(3))


p25_h = {n: diffeq({0: 1.0}, n) for n in range(-1, 5)}
