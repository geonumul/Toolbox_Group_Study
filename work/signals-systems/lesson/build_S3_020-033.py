def fig_lti_shift():
    """p.22: LTI 면 h_k[n] 은 h_0[n] 을 k 칸 민 것."""
    ns = list(range(-1, 6))
    dx, ox, sc = 42, 120, 44
    rows = [(70, [0, 1, 0.5, 0.25, 0, 0, 0], "h0[n]", 1),
            (150, [0, 0, 1, 0.5, 0.25, 0, 0], "h1[n] = h0[n-1]", 2),
            (230, [0, 0, 0, 1, 0.5, 0.25, 0], "h2[n] = h0[n-2]", 3)]
