SKIPK = ("svg", "tex", "sym")


def _txt(o):
    if isinstance(o, str):
        yield o
    elif isinstance(o, list):
        for x in o:
            yield from _txt(x)
    elif isinstance(o, dict):
        for k, v in o.items():
            if k not in SKIPK:
                yield from _txt(v)


