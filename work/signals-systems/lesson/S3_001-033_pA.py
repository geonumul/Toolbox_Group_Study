    _y = lambda x: 1.5 + _C * math.exp(-2 * x)
    _d = (_y(0.3 + 1e-6) - _y(0.3 - 1e-6)) / 2e-6
    assert abs(_d + 2 * _y(0.3) - 3) < 1e-6
