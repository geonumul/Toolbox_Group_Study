_hh = {0: 1, 1: 0.5, 2: 0.25}
assert conv({2: 1}, _hh) == {2: 1, 3: 0.5, 4: 0.25}
# p.19 메아리 직접 계산
def _rec(a, N):
    y, prev = [], 0.0
    for n in range(N):
        prev = (1 if n == 0 else 0) + a * prev
        y.append(prev)
    return y
assert [round(v, 3) for v in _rec(0.7, 4)] == [1, 0.7, 0.49, 0.343]
assert [round(v, 3) for v in _rec(1.3, 3)] == [1, 1.3, 1.69]
assert round(_rec(1.3, 11)[10], 2) == 13.79

