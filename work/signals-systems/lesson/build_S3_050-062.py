def cv(a, b):
    """이산 컨볼루션. 신호는 {n: 값} 사전."""
    r = {}
    for k, va in a.items():
        for m, vb in b.items():
            r[k + m] = r.get(k + m, 0) + va * vb
    return nz(r)


def add(a, b):
    r = dict(a)
    for k, v in b.items():
        r[k] = r.get(k, 0) + v
    return nz(r)


def nz(d):
    return {k: d[k] for k in sorted(d) if abs(d[k]) > 1e-12}


