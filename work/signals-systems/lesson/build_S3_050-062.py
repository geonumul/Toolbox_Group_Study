def K(key, josa=""):
    s = disp(key)
    if not josa:
        return s
    c = TERMS[key][0][-1]
    jong = (ord(c) - 0xAC00) % 28
    if josa == "으로":
        return s + ("로" if jong in (0, 8) else "으로")
    if josa in JOSA:
        return s + (JOSA[josa][0] if jong else JOSA[josa][1])
    return s + josa


