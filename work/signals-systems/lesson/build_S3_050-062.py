def T(o):
    if isinstance(o, str):
        return PH.sub(lambda m: K(m.group(1), m.group(2) or ""), o)
    if isinstance(o, list):
        return [T(x) for x in o]
    if isinstance(o, dict):
        return {k: (v if k in ("svg", "tex", "sym") else T(v)) for k, v in o.items()}
    return o


