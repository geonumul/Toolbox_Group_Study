def run(sysno, x):
    """세 시스템의 출력. x 는 {n: 값} 사전."""
    g = lambda n: x.get(n, 0)
    out = {}
    for n in range(-2, 5):
        if sysno == 1:
            v = g(n) + g(n - 1)
        elif sysno == 2:
            v = (g(n) + g(n - 1)) ** 2
        else:
            v = max(g(n), g(n - 1))
        out[n] = v
    return nz(out)


