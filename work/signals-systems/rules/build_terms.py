import re
def safe(s):
    """엔진 fmt() 숫자 버그 피하기: 연산자 양옆 공백을 붙이고, 공백 사이 숫자 뒤 조사는 붙여 쓴다"""
    s = re.sub(r" ([=<>+/-]) (?=[0-9])", r"\1", s)
    s = re.sub(r"(?<=[0-9A-Za-z)]) ([=<>+/-])(?=[0-9])", r"\1", s)
    s = re.sub(r"(?<= )([0-9]+) (?=[가-힣])", r"\1", s)
    s = re.sub(r"(?<= )([0-9]+) ([=<>])", r"\1\2", s)
    return s

