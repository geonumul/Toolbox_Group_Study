def vec(v, s):
    return ", ".join(f"$x[{s + i}]={fmt(a)}$" for i, a in enumerate(v))


def conv_calc(unit, slides, x, xs, h, hs, ns, model="컨볼루션 합", src=None, extra=""):
    """x 는 xs 칸부터, h 는 hs 칸부터. ns 칸의 y 값을 묻는다"""
    y = conv(x, h)
    ys = xs + hs
    xd = ", ".join(f"$x[{xs + i}]={fmt(a)}$" for i, a in enumerate(x))
    hd = ", ".join(f"$h[{hs + i}]={fmt(a)}$" for i, a in enumerate(h))
    q = (f"LTI 시스템의 **임펄스 응답(Impulse Response)**은 {hd} (나머지 칸은 $0$)이고, 입력은 {xd} (나머지 칸은 $0$)이다. "
         f"**컨볼루션 합(Convolution Sum)** $y[n]=\\sum_k x[k]h[n-k]$ 로 " + ", ".join(f"$y[{n}]$" for n in ns) + " 를 구하시오." + extra)
    nz = [i for i, a in enumerate(y) if a != 0]
    tail = ("" if not nz or (nz[0], nz[-1]) == (0, len(y) - 1)
            else f" 다만 적어 둔 칸 중에 $0$ 인 것이 있어서, 실제로 $0$ 이 아닌 칸은 $n={ys + nz[0]}$ 부터 $n={ys + nz[-1]}$ 까지예요.")
    steps = ["식: $y[n]=\\sum_{k} x[k]\\,h[n-k]$. 입력의 칸마다 $h$ 도장을 크기만큼 찍고 더해요.",
             f"출력이 $0$ 이 아닐 수 있는 칸은 $n={ys}$ 부터 $n={ys + len(y) - 1}$ 까지예요(시작 칸 $={xs}+{hs}$, 길이 $={len(x)}+{len(h)}-1={len(y)}$)." + tail]
    for n in ns:
        terms = []
        for i, a in enumerate(x):
            k = xs + i
            j = n - k - hs
            if 0 <= j < len(h) and a != 0 and h[j] != 0:
                terms.append((k, a, h[j]))
        if terms:
            s = " + ".join(f"x[{k}]h[{n - k}]" for k, a, b in terms)
            v = " + ".join(f"({fmt(a)})({fmt(b)})" for k, a, b in terms)
            steps.append(f"$y[{n}]={s}={v}={fmt(y[n - ys])}$")
        else:
            steps.append(f"$y[{n}]$: 겹치는 칸이 없어서 $0$")
    blanks = [(f"$y[{n}]$", y[n - ys] if 0 <= n - ys < len(y) else 0) for n in ns]
    B.calc(unit, slides, q, "뒤집고, 밀고, 곱하고, 더해서 지정한 칸의 출력을 구해요. 소수 그대로 답해요.", blanks, steps,
           ", ".join(f"$y[{n}]={fmt(b)}$" for n, (l, b) in zip(ns, blanks)),
           "$h[n-k]$ 를 뒤집지 않고 그대로 곱하거나, 시작 칸 번호를 더하지 않아 한 칸씩 밀려 쓰는 실수가 많아요.", model, src)
    return y


