def close(a, b, eps=1e-9):
    assert abs(a - b) < eps, (a, b)


def x_p9(t):
    """S2 p.9 의 x(t): 0~1 에서 1, 1~2 에서 2-t 로 내려감, 나머지 0"""
    if 0 <= t <= 1:
        return 1.0
    if 1 < t <= 2:
        return 2.0 - t
    return 0.0


def conv_calc(unit, slides, x, xs, h, hs, ns, src=None, extra=""):
    """x 는 xs 칸부터, h 는 hs 칸부터. ns 칸의 y 값을 묻는다"""
    y = conv(x, h)
    ys = xs + hs
    xd = ", ".join(f"$x[{xs + i}]={fmt(a)}$" for i, a in enumerate(x))
    hd = ", ".join(f"$h[{hs + i}]={fmt(a)}$" for i, a in enumerate(h))
    q = (f"입력 {xd}, **임펄스 응답(Impulse Response)** {hd} 이다(나머지 칸은 모두 $0$). "
         f"**컨볼루션 합(Convolution Sum)** $y[n]=\\sum_k x[k]h[n-k]$ 로 " + ", ".join(f"$y[{n}]$" for n in ns) + " 를 구하시오." + extra)
    steps = ["식: $y[n]=\\sum_{k} x[k]\\,h[n-k]$. 입력 칸마다 $h$ 도장을 크기만큼 찍고, 같은 칸끼리 더해요.",
             f"출력이 있을 수 있는 칸: 시작 $={xs}+{hs}={ys}$, 길이 $={len(x)}+{len(h)}-1={len(y)}$ 칸."]
    for n in ns:
        terms = []
        for i, a in enumerate(x):
            k = xs + i
            j = n - k - hs
            if 0 <= j < len(h) and a != 0 and h[j] != 0:
                terms.append((k, a, h[j]))
        if terms:
            s = " + ".join(f"x[{k}]h[{n - k}]" for k, a, b in terms)
            v = " + ".join(f"({fmt(a)})({fmt(b)})" for k, a, b in terms)
            steps.append(f"$y[{n}]={s}={v}={fmt(y[n - ys])}$")
        else:
            steps.append(f"$y[{n}]$: 겹치는 칸이 없어서 $0$")
    blanks = [(f"$y[{n}]$", y[n - ys] if 0 <= n - ys < len(y) else 0) for n in ns]
    B.calc(unit, slides, q, "입력 칸마다 메아리 도장을 찍고 같은 칸끼리 더해요. 정수나 소수로 답해요.", blanks, steps,
           ", ".join(f"$y[{n}]={fmt(b)}$" for n, (l, b) in zip(ns, blanks)),
           "$h[n-k]$ 의 칸 번호를 거꾸로 세거나, 시작 칸 번호를 더하지 않아 한 칸씩 밀려 쓰는 실수가 많아요.", "컨볼루션 합", src)
    return y


