def build():
    seen = set()
    out = []
    for ko, en, say, more in TERMS:
        assert len(ko) >= 2, "한 글자 용어는 만들지 않아요: %r" % ko
        assert ko not in seen, ko
        seen.add(ko)
        d = {"ko": ko, "en": en, "say": say}
        if more:
            d["more"] = more
        out.append(d)
    # 1~6주차 용어와 겹치지 않는지 확인
    old = set()
    for w in "123456":
        for t in json.loads((HERE / (w + ".json")).read_text(encoding="utf-8")):
            old.add((t.get("ko") or "").strip())
            old.add((t.get("en") or "").strip())
    dup = [d["ko"] for d in out if d["ko"] in old or (d["en"] and d["en"] in old)]
    assert not dup, "이미 있는 용어예요: %s" % ", ".join(dup)
    txt = json.dumps(out, ensure_ascii=False, indent=1)
    for code in (0x2014, 0x2013, 0x00B7, 0x30FB):
        assert chr(code) not in txt, "금지 문자 %04X" % code
    OUT.write_text(txt, encoding="utf-8")
    print("b.json: 용어 %d개" % len(out))


if __name__ == "__main__":
    build()
