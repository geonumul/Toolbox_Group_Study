def build():
    names = [u["title"] for u in json.loads(UNITS_SRC.read_text(encoding="utf-8"))]
    assert names == [A, B, C, D, E, F], "단원 이름이 units_U9.json 과 달라요"
    out = []
    for t in ("mcq", "ox", "short", "essay"):
        for n, row in enumerate(U9[t], 1):
            qid = "u9-%s-%03d" % (t, n)
            if t == "mcq":
                unit, sl, q, c, e = row
                assert len(c) == 4 and len(set(c)) == 4, qid
                out.append({"id": qid, "type": "mcq", "part": "9", "unit": unit, "slides": sl,
                            "q": q, "c": list(c), "a": 0, "e": e, "level": "basic"})
            elif t == "ox":
                unit, sl, q, a, e = row
                out.append({"id": qid, "type": "ox", "part": "9", "unit": unit, "slides": sl,
                            "q": q, "a": a, "e": e, "level": "basic"})
            elif t == "short":
                unit, sl, q, a, e = row
                out.append({"id": qid, "type": "short", "part": "9", "unit": unit, "slides": sl,
                            "q": q, "a": a, "e": e, "level": "basic"})
            else:
                unit, sl, q, pts, ans, model = row
                out.append({"id": qid, "type": "essay", "part": "9", "unit": unit, "slides": sl,
                            "q": q, "points": pts, "answer": ans, "model": model, "level": "basic"})
    # ------------------------------------------------- 보기 자리 섞기와 id 고정
    # 정답을 늘 첫 자리에 적었으므로, 파일에 쓰기 직전에 보기 자리를 섞는다(까닭과 예외는 optshuffle.py 에).
    stats = {}
    optshuffle.shuffle_bank(out, stats)
    assert not stats["locked"], "섞이지 않고 첫 자리에 남은 문항: %r" % stats["locked"]
    # id 는 목록 안 자리로 매긴다. 문항을 맨 뒤가 아닌 곳에 끼우면 그 뒤 id 가 밀리므로 박아 둔다.
    IDS = (["u9-mcq-%03d" % i for i in range(1, 16)] + ["u9-ox-%03d" % i for i in range(1, 10)]
           + ["u9-short-%03d" % i for i in range(1, 9)] + ["u9-essay-%03d" % i for i in range(1, 4)])
    optshuffle.check_ids(out, IDS)

    txt = json.dumps(out, ensure_ascii=False, indent=1)
    for code in (0x2014, 0x2013, 0x00B7, 0x30FB, 0x2022):
        assert chr(code) not in txt, "금지 문자 U+%04X" % code
    OUT.write_text(txt, encoding="utf-8")
    from collections import Counter
    print(len(out), dict(Counter(q["type"] for q in out)), "정답 자리", stats["used"][:4])
    print(dict(Counter(q["unit"] for q in out)))


