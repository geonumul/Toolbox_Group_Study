def build():
    out = []
    part = "8"
    for t in ("mcq", "ox", "short", "essay"):
        for n, row in enumerate(U8[t], 1):
            qid = f"u{part}-{t}-{n:03d}"
            if t == "mcq":
                unit, sl, q, c, e = row
                assert len(c) == 4 and len(set(c)) == 4, qid
                order = list(range(4))
                random.Random(int(hashlib.md5(qid.encode()).hexdigest()[:8], 16)).shuffle(order)
                out.append({"id": qid, "type": "mcq", "part": part, "unit": unit, "slides": sl, "q": q,
                            "c": [c[i] for i in order], "a": order.index(0), "e": e, "level": "basic"})
            elif t == "ox":
                unit, sl, q, a, e = row
                out.append({"id": qid, "type": "ox", "part": part, "unit": unit, "slides": sl, "q": q,
                            "a": a, "e": e, "level": "basic"})
            elif t == "short":
                unit, sl, q, a, e = row
                out.append({"id": qid, "type": "short", "part": part, "unit": unit, "slides": sl, "q": q,
                            "a": a, "e": e, "level": "basic"})
            else:
                unit, sl, q, pts, ans, model = row
                out.append({"id": qid, "type": "essay", "part": part, "unit": unit, "slides": sl, "q": q,
                            "points": pts, "answer": ans, "model": model, "level": "basic"})
    # 단원 이름은 units_U8.json 과 한 글자도 다르지 않아야 한다
    units = json.loads((pathlib.Path(__file__).parent.parent / "_src" / "units_U8.json").read_text(encoding="utf-8"))
    names = [u["title"] for u in units]
    assert names == [U1, U2, U3, U4, U5], names
    assert {q["unit"] for q in out} == set(names), "모든 단원에 문항이 있어야 한다"
    # ox 는 절반쯤 false
    ox = [q["a"] for q in out if q["type"] == "ox"]
    assert abs(ox.count(True) - ox.count(False)) <= 1, ox
    # 금지 문자
    txt = json.dumps(out, ensure_ascii=False)
    for code in (0x2014, 0x2013, 0x00B7, 0x30FB, 0x2022):
        assert chr(code) not in txt, hex(code)
    # ------------------------------------------------- 보기 자리 섞기와 id 고정
    optshuffle.shuffle_bank(out)
    IDS = (["u8-mcq-%03d" % i for i in range(1, 14)] + ["u8-ox-%03d" % i for i in range(1, 9)]
           + ["u8-short-%03d" % i for i in range(1, 8)] + ["u8-essay-%03d" % i for i in range(1, 4)])
    optshuffle.check_ids(out, IDS)

    OUT.write_text(json.dumps(out, ensure_ascii=False, indent=1), encoding="utf-8")
    from collections import Counter
    print(len(out), dict(Counter(q["type"] for q in out)), dict(Counter(q["unit"][:3] for q in out)))


if __name__ == "__main__":
    build()
