def _strings(o):
    if isinstance(o, str):
        yield o
    elif isinstance(o, list):
        for x in o:
            yield from _strings(x)
    elif isinstance(o, dict):
        for kk, v in o.items():
            if kk != "svg":
                yield from _strings(v)


def main():
    problems = []
    for u in UNITS:
        body = " ".join(_strings(u["slides"])).lower()
        for t in u["terms"]:
            n = max(body.count(t["en"].lower()) if t["en"] else 0, body.count(t["ko"].lower()) if t["ko"] else 0)
            if n < 3:
                problems.append(f"{u['id']} {t['ko'] or t['en']} {n}번")
            assert len(t["ko"] or t["en"]) >= 2, t
        for s in u["slides"]:
            if s["kind"] == "figure":
                assert all(int(v) <= 3 for v in re.findall(r'rx="(\d+)"', s["svg"]))
    d = {"week": "3", "title": "3주차. 2강 친환경 재료", "units": UNITS}
    raw = json.dumps(d, ensure_ascii=False, indent=1)
    for ch in ("—", "–", "·", "・"):
        assert ch not in raw, repr(ch)
    for p in problems:
        print("용어 부족:", p)
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(raw)
    # 주차 용어집: 단원 용어 전부(설명 more 포함) + 슬라이드에만 나온 이름
    gl, seen = [], set()
    for t in [t for u in UNITS for t in u["terms"]] + EXTRA_TERMS:
        key = (t["en"] or t["ko"]).lower()
        if key in seen:
            continue
        seen.add(key)
        gl.append(t)
    graw = json.dumps(gl, ensure_ascii=False, indent=1)
    for ch in ("—", "–", "·", "・"):
        assert ch not in graw, repr(ch)
    os.makedirs(os.path.dirname(TERMS_OUT), exist_ok=True)
    with open(TERMS_OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(graw)
    print("저장:", OUT, "단원", len(UNITS), "슬라이드", sum(len(u["slides"]) for u in UNITS), "/ 용어집", len(gl))


if __name__ == "__main__":
    main()
