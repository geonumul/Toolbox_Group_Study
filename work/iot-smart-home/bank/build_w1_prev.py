def fix(o):
    if isinstance(o, str):
        for a, b in TEXT_FIX.items():
            o = o.replace(a, b)
        return o
    if isinstance(o, list):
        return [fix(x) for x in o]
    if isinstance(o, dict):
        return {k: fix(v) for k, v in o.items()}
    return o


