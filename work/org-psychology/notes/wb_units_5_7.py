A_CLASS = [60, 70, 80, 90, 100]
B_CLASS = [78, 79, 80, 81, 82]


def mean(xs):
    return sum(xs) / len(xs)


def sd(xs):
    m = mean(xs)
    return math.sqrt(sum((x - m) ** 2 for x in xs) / len(xs))


MA, MB = mean(A_CLASS), mean(B_CLASS)
RA, RB = max(A_CLASS) - min(A_CLASS), max(B_CLASS) - min(B_CLASS)
SA, SB = sd(A_CLASS), sd(B_CLASS)
assert MA == 80 and MB == 80, (MA, MB)
assert RA == 40 and RB == 4, (RA, RB)
assert sum((x - MA) ** 2 for x in A_CLASS) == 1000
assert sum((x - MB) ** 2 for x in B_CLASS) == 10
assert round(SA, 2) == 14.14 and round(SB, 2) == 1.41, (SA, SB)
LO68, HI68 = 70 - 10, 70 + 10
