import json
import pathlib

import optshuffle

HERE = pathlib.Path(__file__).resolve().parent


class Bank:
    """문제은행 생성 도우미 (signals-systems/bank/sigbank_util.py 와 같은 모양)."""

    def __init__(self, prefix, part, level):
        self.prefix, self.part, self.level = prefix, part, level
        self.items, self.n = [], {}

    def _id(self, t):
        self.n[t] = self.n.get(t, 0) + 1
        return f"{self.prefix}-{t}-{self.n[t]:03d}"

    def _base(self, t, unit, slides, src):
        d = {"id": self._id(t), "type": t, "part": self.part, "level": self.level,
             "unit": unit, "slides": slides}
        if src:
            d["src"] = src
        return d

    def mcq(self, unit, slides, q, c, a, e, src=None):
        assert len(c) == 4 and len(set(c)) == 4 and 0 <= a < 4, q
        d = self._base("mcq", unit, slides, src)
        d.update(q=q, c=c, a=a, e=e)
        self.items.append(d)

    def ox(self, unit, slides, q, a, e, src=None):
        assert isinstance(a, bool)
        d = self._base("ox", unit, slides, src)
        d.update(q=q, a=a, e=e)
        self.items.append(d)

    def short(self, unit, slides, q, a, e, src=None):
        assert isinstance(a, (list, tuple)) and a
        d = self._base("short", unit, slides, src)
        d.update(q=q, a=[str(x) for x in a], e=e)
        self.items.append(d)

    def essay(self, unit, slides, q, answer, points, model, src=None):
        assert 4 <= len(points) <= 10, q
        d = self._base("essay", unit, slides, src)
        d.update(q=q, answer=answer, points=points, model=model)
        self.items.append(d)

    def save(self, name, ids):
        """ids 는 만들어질 문항의 id 목록이다(optshuffle.check_ids 설명 참고)."""
        # 정답이 한 자리에 몰리면 내용을 몰라도 같은 번호만 찍어 맞힐 수 있다. 그래서
        # 파일에 쓰기 직전에 보기 자리를 섞는다(까닭과 예외는 optshuffle.py 에).
        optshuffle.shuffle_bank(self.items)
        optshuffle.check_ids(self.items, ids)
        raw = json.dumps(self.items, ensure_ascii=False, indent=1)
        for ch in "—–·・":
            assert ch not in raw, ch
        (HERE / name).write_text(raw, encoding="utf-8")
        cnt, blank = {}, 0
        for q in self.items:
            cnt[q["type"]] = cnt.get(q["type"], 0) + 1
            if q.get("src") == "빈칸":
                blank += 1
        print(name, len(self.items), cnt, "빈칸", blank)


