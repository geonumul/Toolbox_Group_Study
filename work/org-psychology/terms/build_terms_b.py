def main():
    have = set()
    for e in json.load(open(DICT, encoding="utf-8")):
        for k in ((e.get("ko") or "").strip(), (e.get("en") or "").strip()):
            if k:
                have.add(k)
    out, seen = [], set()
    for ko, en, say, more in T:
        assert ko not in have, "용어사전에 이미 있는 말: %s" % ko
        assert ko not in seen, "중복: %s" % ko
        assert len(ko) >= 2, "한 글자 용어 금지: %s" % ko
        seen.add(ko)
        out.append({"ko": ko, "en": en, "say": say, "more": more})
    raw = json.dumps(out, ensure_ascii=False, indent=1)
    for code in (0x2014, 0x2013, 0x00B7, 0x30FB):   # em dash, en dash, 가운뎃점 2종
        assert chr(code) not in raw, "금지 문자 %r" % chr(code)
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(raw)
    print("b.json: 새 용어 %d개" % len(out))


if __name__ == "__main__":
    main()
