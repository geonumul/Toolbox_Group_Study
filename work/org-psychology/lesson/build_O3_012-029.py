def pair_slide(p, a, b, question, line_a, line_b, ana_head, ana_scene, ana_map,
               boxes_left, boxes_right, checks, terms, extra2=(), warn_frame=None):
    """사회화 책략 한 쌍(p.13~18) 의 공통 뼈대"""
    t_a, t_b = f"**{a} 책략({dict(EN)[a]})**", f"**{b} 책략({dict(EN)[b]})**"
    s = {"p": p, "title": f"사회화 책략: {a} vs {b}",
         "terms": terms,
         "pass1": [say(f"**사회화 책략(Socialization Tactics)**의 {PAIRS.index((a, b)) + 1}번째 쌍이에요. {t_a}과 {t_b}이에요.",
                       f"이 쌍이 답하는 질문은 '{question}' 예요."),
                   ana(ana_head, ana_scene, ana_map)],
         "pass2": [cmp(f"{a} vs {b}", ["", "슬라이드 설명", "결과"],
                       [(t_a, line_a[0], line_a[1]), (t_b, line_b[0], line_b[1])])] + list(extra2)
                  + [chk(*checks[0])],
         "pass3": [D.look(p, "제목과 정의 두 줄",
                    ((0.0, 0.02, 0.4, 0.10), "왼쪽 위 제목 띠: 조직 사회화: 조직의 관점."),
                    ((0.0, 0.13, 0.6, 0.20), "동그라미 제목: 사회화 책략(van Maanen & Schein, 1979)."),
                    ((0.05, 0.24, 0.32, 0.30), f"초록 상자 두 개: {a} - {b}."),
                    ((0.32, 0.24, 0.95, 0.30), f"오른쪽 질문 한 줄: {question}"),
                    ((0.0, 0.32, 0.99, 0.37), f"- {a}: {line_a[0]} → {line_a[1]}"),
                    ((0.0, 0.37, 0.99, 0.43), f"- {b}: {line_b[0]} → {line_b[1]}")),
                   D.look(p, f"왼쪽 그림 속 말({a} 쪽)", *boxes_left),
                   D.look(p, f"오른쪽 그림 속 말({b} 쪽)", *boxes_right)],
         "pass4": [],
         "pass5": [chk(*c) for c in checks[1:]]}
    if warn_frame:
        s["pass5"].append(warn_frame)
    return s


