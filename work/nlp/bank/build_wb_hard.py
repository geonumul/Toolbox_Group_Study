# --- H8 경사 하강법
def gd(w, lr, n):
    out = [w]
    for _ in range(n):
        w = w - lr * 2 * (w - 3)
        out.append(w)
    return out


small = gd(0.0, 0.1, 3)
assert [round(v, 4) for v in small] == [0.0, 0.6, 1.08, 1.464]
big = gd(0.0, 1.2, 2)
assert [round(v, 4) for v in big] == [0.0, 7.2, -2.88]     # 건너뛰고 반대쪽으로 더 멀리 튀어요
assert (big[1] - 3) ** 2 > (big[0] - 3) ** 2        # 손실이 오히려 커졌어요
assert round((big[1] - 3) ** 2, 4) == 17.64 and (big[0] - 3) ** 2 == 9.0
good = gd(0.0, 0.5, 1)
assert round(good[1], 4) == 3.0                      # 한 번에 정확히 도착

# --- H9 선형 두 층은 한 층
W1 = np.array([[1.0, 2.0], [0.0, 1.0]])
W2 = np.array([[1.0, 1.0], [2.0, 0.0]])
xv = np.array([1.0, 1.0])
assert [list(r) for r in (W2 @ W1)] == [[1.0, 3.0], [2.0, 4.0]]
assert list(W2 @ (W1 @ xv)) == list((W2 @ W1) @ xv) == [4.0, 6.0]
# ReLU 를 끼우면 달라진다
relu = lambda z: np.maximum(z, 0.0)
xn = np.array([1.0, -3.0])
assert not np.allclose(W2 @ relu(W1 @ xn), (W2 @ W1) @ xn)
assert list(W1 @ xn) == [-5.0, -3.0]
assert list(relu(W1 @ xn)) == [0.0, 0.0]
assert list(W2 @ relu(W1 @ xn)) == [0.0, 0.0]
assert list((W2 @ W1) @ xn) == [-8.0, -10.0]

