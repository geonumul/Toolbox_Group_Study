def softmax(z):
    z = np.asarray(z, dtype=float)
    z = z - z.max()
    e = np.exp(z)
    return e / e.sum()


# --- H1 내적과 코사인이 순위를 다르게 주는 예
hq = np.array([1.0, 0.0])
hd1 = np.array([10.0, 10.0])
hd2 = np.array([2.0, 0.0])
assert float(hq @ hd1) == 10.0 and float(hq @ hd2) == 2.0
cos1 = float(hq @ hd1 / (np.linalg.norm(hq) * np.linalg.norm(hd1)))
cos2 = float(hq @ hd2 / (np.linalg.norm(hq) * np.linalg.norm(hd2)))
assert round(cos1, 4) == 0.7071 and round(cos2, 4) == 1.0
assert (hq @ hd1) > (hq @ hd2) and cos1 < cos2      # 순위가 뒤집혀요
assert round(float(np.linalg.norm(hd1)), 4) == 14.1421

# --- H2 원-핫의 낭비
V = 50000
assert V * 1 == 50000 and V - 1 == 49999          # 1 하나, 나머지는 전부 0
assert 50000 / 300 > 166                           # 임베딩 300칸과 비교

# --- H3 shape 체인과 전치 규칙
Ah = np.zeros((2, 3))
Bh = np.zeros((3, 4))
assert (Ah @ Bh).shape == (2, 4)
assert (Ah @ Bh).T.shape == (4, 2)
assert (Bh.T @ Ah.T).shape == (4, 2)               # (AB)^T = B^T A^T
assert (np.zeros((4, 6)) @ np.zeros((6, 3)) @ np.zeros((3, 5))).shape == (4, 5)
# 멀티 헤드
assert 512 // 8 == 64 and 8 * 64 == 512

# --- H4 로그는 순서를 바꾸지 않는다
assert math.log(0.3) > math.log(0.2)
assert round(math.log(0.3), 4) == -1.204 and round(math.log(0.2), 4) == -1.6094
# PPL = exp(평균 음의 로그)
qs4 = [0.25, 0.25, 0.25, 0.25]
assert round(math.exp(float(-np.mean(np.log(qs4)))), 4) == 4.0
qs5 = [0.5, 0.5, 0.125, 0.125]
nll5 = float(-np.mean(np.log(qs5)))
assert round(nll5, 4) == 1.3863 and round(math.exp(nll5), 4) == 4.0
# 아주 작은 곱
tiny = [1e-3] * 5
assert round(float(np.sum(np.log(tiny))), 4) == -34.5388
assert abs(float(np.prod(tiny)) - 1e-15) < 1e-20

# --- H5 조건부 확률
# 말뭉치: "나는 밥을 먹었다", "나는 빵을 먹었다", "너는 밥을 먹었다"
c_나는 = 2
