# --- H6 소프트맥스: 더하기는 불변, 곱하기는 뾰족
base = np.array([2.0, 1.0, 0.0])
assert np.allclose(softmax(base), softmax(base + 100))
sharp = softmax(base * 2)
flat = softmax(base * 0.5)
assert [round(float(t), 4) for t in sharp] == [0.8668, 0.1173, 0.0159]
assert [round(float(t), 4) for t in flat] == [0.5065, 0.3072, 0.1863]
assert round(float(softmax(base).max()), 4) == 0.6652
assert sharp.max() > softmax(base).max() > flat.max()
# 포화
assert round(float(softmax([20.0, 0.0, 1.0]).max()), 6) == 1.0

