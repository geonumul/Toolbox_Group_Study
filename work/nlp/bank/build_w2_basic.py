bank = []
cnt = {}


def add(t, unit, slides, src=None, **kw):
    cnt[t] = cnt.get(t, 0) + 1
    item = {"id": f"w2b-{t}-{cnt[t]:03d}", "type": t, "part": "2", "level": "basic",
            "unit": unit, "slides": slides}
    if src:
        item["src"] = src
    item.update(kw)
    bank.append(item)


def mcq(unit, slides, q, c, a, e, src=None):
    add("mcq", unit, slides, src, q=q, c=c, a=a, e=e)


def ox(unit, slides, q, a, e, src=None):
    add("ox", unit, slides, src, q=q, a=a, e=e)


def short(unit, slides, q, a, e, src=None, num=False, tol=None):
    kw = dict(q=q, a=a, e=e)
    if num:
        kw["num"] = True
        kw["tol"] = tol if tol is not None else 0.01
    add("short", unit, slides, src, **kw)


def essay(unit, slides, model, q, answer, points, src=None):
    add("essay", unit, slides, src, model=model, q=q, answer=answer, points=points)


def calc(unit, slides, model, q, qko, blanks, steps, answer, e, src=None):
    add("calc", unit, slides, src, model=model, q=q, qko=qko, blanks=blanks,
        steps=steps, answer=answer, e=e)


