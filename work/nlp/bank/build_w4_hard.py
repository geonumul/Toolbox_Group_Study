# --- H7 위치 인코딩 두 자리의 차이
def pe_row(pos, dd=4):
    out = []
    for i in range(dd // 2):
        ang = pos / (10000 ** (2 * i / dd))
        out += [math.sin(ang), math.cos(ang)]
    return np.array(out)


p1, p2 = pe_row(1), pe_row(2)
assert [round(float(v), 4) for v in p1] == [0.8415, 0.5403, 0.01, 1.0]
assert [round(float(v), 4) for v in p2] == [0.9093, -0.4161, 0.02, 0.9998]
diff = float(np.linalg.norm(p1 - p2))
assert round(diff, 4) == 0.9589

# --- H8 LayerNorm
x8 = np.array([2.0, 4.0, 4.0, 10.0])
mu8 = float(x8.mean())
var8 = float(((x8 - mu8) ** 2).mean())
sd8 = math.sqrt(var8)
z8 = (x8 - mu8) / sd8
assert mu8 == 5.0 and var8 == 9.0 and sd8 == 3.0
assert [round(float(v), 4) for v in z8] == [-1.0, -0.3333, -0.3333, 1.6667]
assert abs(float(z8.mean())) < 1e-12 and abs(float((z8 ** 2).mean()) - 1.0) < 1e-12

