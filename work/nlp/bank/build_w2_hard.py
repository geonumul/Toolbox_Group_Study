def pair_counts(cp):
    p = Counter()
    for w, f in cp.items():
        for i in range(len(w) - 1):
            p[(w[i], w[i + 1])] += f
    return p


def merge(cp, pair):
    a, b = pair
    out = {}
    for w, f in cp.items():
        nw, i = [], 0
        while i < len(w):
            if i < len(w) - 1 and w[i] == a and w[i + 1] == b:
                nw.append(a + b); i += 2
            else:
                nw.append(w[i]); i += 1
        out[tuple(nw)] = f
    return out


def train(cp, n):
    merges, counts = [], []
    for _ in range(n):
        p = pair_counts(cp)
        if not p:
            break
        best = max(p, key=p.get)
        cp = merge(cp, best)
        merges.append(best); counts.append(p[best])
    return cp, merges, counts


def tokenize(word, merges):
    s = list(word) + ["</w>"]
    for a, b in merges:
        i = 0
        while i < len(s) - 1:
            if s[i] == a and s[i + 1] == b:
                s[i:i + 2] = [a + b]
            else:
                i += 1
    return s


def sig(x):
    return 1 / (1 + math.exp(-x))


def cosv(u, v):
    return sum(x * y for x, y in zip(u, v)) / (math.sqrt(sum(x * x for x in u)) * math.sqrt(sum(y * y for y in v)))


