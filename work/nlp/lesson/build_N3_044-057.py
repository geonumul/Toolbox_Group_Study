# p.53 기울기 클리핑
g = np.array([3.0, 4.0])
gn = float(np.linalg.norm(g))
assert gn == 5.0
clip1 = 1.0 * g / gn
clip2 = 2.0 * g / gn
assert [round(float(v), 4) for v in clip1] == [0.6, 0.8]
assert [round(float(v), 4) for v in clip2] == [1.2, 1.6]
assert abs(float(np.linalg.norm(clip2)) - 2.0) < 1e-12
# 방향은 그대로예요 (단위 벡터가 같아요)
assert np.allclose(clip1 / np.linalg.norm(clip1), g / gn)

