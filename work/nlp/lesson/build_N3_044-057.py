# p.47 RNN 한 걸음 손계산
Wh = np.array([[0.5, 0.0], [0.0, 0.5]])
We = np.array([[1.0, 0.0], [0.0, -1.0]])
h0 = np.array([0.0, 0.0])
e1 = np.array([1.0, 1.0])
h1 = np.tanh(Wh @ h0 + We @ e1)
assert [round(float(v), 4) for v in h1] == [0.7616, -0.7616]
assert round(math.tanh(1.0), 4) == 0.7616
h2 = np.tanh(Wh @ h1 + We @ e1)
assert [round(float(v), 4) for v in h2] == [0.8811, -0.8811]

