def dot(a, b):
    return sum(x * y for x, y in zip(a, b))


def softmax(xs):
    m = max(xs)
    e = [math.exp(x - m) for x in xs]
    s = sum(e)
    return [v / s for v in e]


# p.21 슬라이드의 점수 3.6, 0.8, 0.5, 0.4 를 그대로 만드는 작은 예
s_t = [1.0, 2.0]
H = [[3.0, 0.3], [0.4, 0.2], [0.1, 0.2], [0.2, 0.1]]
scores = [dot(s_t, h) for h in H]
assert [round(v, 2) for v in scores] == [3.6, 0.8, 0.5, 0.4]

# p.22 소프트맥스 -> 슬라이드의 0.87, 0.05, 0.04, 0.04
alpha = softmax(scores)
assert [round(v, 2) for v in alpha] == [0.87, 0.05, 0.04, 0.04]
assert abs(sum(alpha) - 1.0) < 1e-12
assert [round(v, 4) for v in alpha] == [0.8721, 0.0530, 0.0393, 0.0355]
# 본문은 소수 셋째 자리로 반올림한 (0.872, 0.053, 0.039, 0.036) 을 쓴다
alpha3 = [round(v, 3) for v in alpha]
assert alpha3 == [0.872, 0.053, 0.039, 0.036]

# p.23 문맥 벡터 = 가중합
ctx = [sum(a * h[j] for a, h in zip(alpha, H)) for j in range(2)]
