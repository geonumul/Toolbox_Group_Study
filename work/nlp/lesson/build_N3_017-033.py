PW, PH = 1400, 788


def say(*lines):
    return {"kind": "say", "lines": list(lines)}


def look(head, *boxes):
    out = []
    for x1, y1, x2, y2, s in boxes:
        out.append({"x": round(x1 / PW, 3), "y": round(y1 / PH, 3),
                    "w": round((x2 - x1) / PW, 3), "h": round((y2 - y1) / PH, 3), "say": s})
    return {"kind": "look", "head": head, "boxes": out}


