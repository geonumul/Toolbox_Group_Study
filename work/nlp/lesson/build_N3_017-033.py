FIN = {"w2v": 0, "relu": 0, "autograd": 0}


def _fin(key):
    if key in FIN:
        return FIN[key]
    c = TERMS[key][0][-1]
    jong = (ord(c) - 0xAC00) % 28
    return 0 if jong == 0 else (2 if jong == 8 else 1)


def disp(key):
    if key in DISP:
        return DISP[key]
    ko, en = TERMS[key][:2]
    return f"**{ko}({en})**"


def K(key, josa=""):
    s = disp(key)
    if not josa:
        return s
    f = _fin(key)
    if josa == "으로":
        return s + ("으로" if f == 1 else "로")
    return s + (JOSA[josa][0] if f >= 1 else JOSA[josa][1])


