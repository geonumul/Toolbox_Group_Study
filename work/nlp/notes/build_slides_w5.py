def _c(cls, b):
    return f"{cls} b{b}" if b else cls


def TX(x, y, s, cls="t", size=14, b=0, anchor="middle"):
    return f'<text class="{_c(cls, b)}" x="{x}" y="{y}" font-size="{size}" text-anchor="{anchor}">{s}</text>'


def R(x, y, w, h, cls="n", b=0):
    return f'<rect class="{_c(cls, b)}" x="{x}" y="{y}" width="{w}" height="{h}" rx="2"/>'


def L(x1, y1, x2, y2, cls="e", b=0):
    return f'<line class="{_c(cls, b)}" x1="{x1}" y1="{y1}" x2="{x2}" y2="{y2}"/>'


def A(x1, y1, x2, y2, cls="e2", b=0):
    ang = math.atan2(y2 - y1, x2 - x1)
    s = 8
    p1 = (x2 - s * math.cos(ang) + s * 0.5 * math.sin(ang), y2 - s * math.sin(ang) - s * 0.5 * math.cos(ang))
    p2 = (x2 - s * math.cos(ang) - s * 0.5 * math.sin(ang), y2 - s * math.sin(ang) + s * 0.5 * math.cos(ang))
    lx, ly = x2 - s * 0.8 * math.cos(ang), y2 - s * 0.8 * math.sin(ang)
    pts_ = f"{x2},{y2} {p1[0]:.1f},{p1[1]:.1f} {p2[0]:.1f},{p2[1]:.1f}"
    return L(x1, y1, round(lx, 1), round(ly, 1), cls, b) + f'<polygon class="{_c("arrow", b)}" points="{pts_}"/>'


def GRID(x0, y0, cell, n, keep, cls_on, b):
    out = []
    for r in range(n):
        for c in range(n):
            out.append(R(x0 + c * cell, y0 + r * cell, cell - 1, cell - 1, cls_on if keep(r, c) else "n", b))
    return "".join(out)


def SVG(*els):
    return S0 + "".join(els) + "</svg>"


