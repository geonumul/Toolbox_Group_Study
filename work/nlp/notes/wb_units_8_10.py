# 손실 L(w) = w^2, 기울기 dL/dw = 2w, 학습률 0.25
LR = 0.25


def step_once(w, lr):
    return w - lr * (2 * w)


WALK = [4.0]
for _ in range(3):
    WALK.append(step_once(WALK[-1], LR))
assert WALK == [4.0, 2.0, 1.0, 0.5]
LOSS = [w * w for w in WALK]
assert LOSS == [16.0, 4.0, 1.0, 0.25]
assert 4.0 - LR * (2 * 4.0) == 2.0

# 보폭이 1 이면 제자리 뜀, 1.5 면 더 나빠짐
BOUNCE = [4.0]
for _ in range(2):
    BOUNCE.append(step_once(BOUNCE[-1], 1.0))
assert BOUNCE == [4.0, -4.0, 4.0]
assert [w * w for w in BOUNCE] == [16.0, 16.0, 16.0]
BIG = [4.0]
for _ in range(2):
    BIG.append(step_once(BIG[-1], 1.5))
assert BIG == [4.0, -8.0, 16.0]
assert [w * w for w in BIG] == [16.0, 64.0, 256.0]

