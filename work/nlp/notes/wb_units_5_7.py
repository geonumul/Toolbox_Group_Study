def n2(v):
    return "%.2f" % v


def n3(v):
    return "%.3f" % v


def nt(v, d=2):
    """꼬리의 0 을 떼어 쓴 숫자 (0.50 -> 0.5)."""
    t = ("%." + str(d) + "f") % v
    return t.rstrip("0").rstrip(".") if "." in t else t


