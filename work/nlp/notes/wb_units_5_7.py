def f7(x):
    return x * x


assert f7(3) == 9
D01 = (f7(3.1) - f7(3)) / 0.1
D001 = (f7(3.01) - f7(3)) / 0.01
assert n2(f7(3.1)) == "9.61" and n2(f7(3.1) - f7(3)) == "0.61"
assert n2(D01) == "6.10" and n2(D001) == "6.01"
assert 2 * 3 == 6

# 미분 규칙: g(x) = 5x^2 + x^3 -> g'(x) = 10x + 3x^2
def g7(x):
    return 5 * x * x + x ** 3


def dg7(x):
    return 10 * x + 3 * x * x


assert g7(2) == 28 and dg7(2) == 32
assert abs((g7(2.0001) - g7(2)) / 0.0001 - 32) < 1e-2

# 접선: y = x^2 의 x=3 에서 접선은 y = 6x - 9
def tan7(x):
    return 6 * x - 9


assert tan7(3) == 9 and f7(3) == 9
assert tan7(4) == 15 and f7(4) == 16

# 연쇄 법칙: u = 3x + 1, y = u^2, x = 1
def u7(x):
    return 3 * x + 1


assert u7(1) == 4 and f7(u7(1)) == 16
DYDU, DUDX = 2 * u7(1), 3
assert DYDU == 8 and DUDX == 3 and DYDU * DUDX == 24
assert 18 * 1 + 6 == 24                       # 직접 전개: y = 9x^2 + 6x + 1
assert n2((f7(u7(1.01)) - f7(u7(1))) / 0.01) == "24.09"

# 편미분: F(x, y) = x^2 + 3xy, (2, 1) 에서
def F7(x, y):
    return x * x + 3 * x * y


assert F7(2, 1) == 10
FX, FY = 2 * 2 + 3 * 1, 3 * 2
assert FX == 7 and FY == 6
assert n2((F7(2.01, 1) - F7(2, 1)) / 0.01) == "7.01"
assert n2((F7(2, 1.01) - F7(2, 1)) / 0.01) == "6.00"


