# ================================================================ wb-6 숫자
def softmax_raw(z):
    e = [math.exp(v) for v in z]
    s = sum(e)
    return [x / s for x in e]


def softmax_safe(z):
    m = max(z)
    e = [math.exp(v - m) for v in z]
    s = sum(e)
    return [x / s for x in e]


Z = [2.0, 1.0, 0.0]
EXPZ = [math.exp(v) for v in Z]
SUMZ = sum(EXPZ)
P6 = softmax_raw(Z)
assert [n3(v) for v in EXPZ] == ["7.389", "2.718", "1.000"]
assert n3(SUMZ) == "11.107"
assert [n3(v) for v in P6] == ["0.665", "0.245", "0.090"]
assert abs(sum(P6) - 1.0) < 1e-12

# 최댓값 빼기: 답이 그대로인지 확인
ZS = [v - max(Z) for v in Z]
EXPS = [math.exp(v) for v in ZS]
SUMS = sum(EXPS)
assert ZS == [0.0, -1.0, -2.0]
assert [n3(v) for v in EXPS] == ["1.000", "0.368", "0.135"]
assert n3(SUMS) == "1.503"
assert [n3(v) for v in softmax_safe(Z)] == [n3(v) for v in P6]

# 아주 큰 점수: 그냥 exp 를 씌우면 터지고, 최댓값을 빼면 멀쩡하다
BIG = [1000.0, 999.0, 998.0]
try:
    math.exp(BIG[0])
    OVERFLOWED = False
except OverflowError:
    OVERFLOWED = True
assert OVERFLOWED
assert [n3(v) for v in softmax_safe(BIG)] == [n3(v) for v in P6]

# 모든 점수에 같은 수를 더해도 결과가 같다
assert [n3(v) for v in softmax_raw([v + 5 for v in Z])] == [n3(v) for v in P6]

# 교차 엔트로피
CE1 = -math.log(P6[0])
CE3 = -math.log(P6[2])
assert n3(CE1) == "0.408" and n3(CE3) == "2.408"
assert abs((CE3 - CE1) - 2.0) < 1e-12
CE_UNI = -math.log(1.0 / 3)
assert n3(CE_UNI) == "1.099"
PPL1 = math.exp(CE1)
PPL_UNI = math.exp(CE_UNI)
assert n3(PPL1) == "1.503" and abs(PPL_UNI - 3.0) < 1e-9

# 점수를 반으로 줄이거나 두 배로 키우면 분포가 얼마나 뾰족해지나
P_HALF = softmax_raw([v * 0.5 for v in Z])
P_DBL = softmax_raw([v * 2.0 for v in Z])
assert [n2(v) for v in P_HALF] == ["0.51", "0.31", "0.19"]
assert [n2(v) for v in P6] == ["0.67", "0.24", "0.09"]
assert [n2(v) for v in P_DBL] == ["0.87", "0.12", "0.02"]

# 점수를 10배로 키우면 거의 원-핫 (N4 p.38 포화)
P_SAT = softmax_safe([20.0, 10.0, 0.0])
assert n3(P_SAT[0]) == "1.000" and abs(P_SAT[0] - 0.9999546) < 1e-6
assert abs(P_SAT[1] - 4.5398e-5) < 1e-8

# numpy 로 한 번 더 교차 검증
_np = np.exp(np.array(Z) - np.max(Z))
assert np.allclose(_np / _np.sum(), np.array(P6))


